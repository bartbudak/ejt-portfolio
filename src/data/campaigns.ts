/** A name inside `body` that should be a link. Matched as plain text, so the
 *  `text` has to appear in `body` exactly once. */
export interface BriefLink {
  text: string;
  href: string;
}

export interface BriefRow {
  label: string;
  body: string;
  /** Written here rather than by Ellie — needs her review. */
  drafted?: boolean;
  /**
   * Names in `body` that her deck hyperlinks, so they link out here too rather
   * than sitting as flat text (Ellie, 2026-09-11). Kept beside the copy rather
   * than inlined as markup so `body` stays one plain string she can diff
   * against her own deck.
   */
  links?: BriefLink[];
}

/** How the deck arranges a given band. Each season is laid out differently in
 *  her Canva, so this is per-collection rather than one template. */
export interface BandLayout {
  /** Heading alignment. Fall and Holiday centre theirs; the rest sit left. */
  align: "left" | "center";
  /** Where "In a nutshell" sits relative to the heading. Holiday puts it above;
   *  the Dungeon Crawler Carl band has no script line at all. */
  nutshell: "inline" | "below" | "above" | "none";
  /** Where the motif art goes. Fall runs apples across the top, Spring borders
   *  the bottom with flowers, Holiday hangs lights from both top corners. */
  motifs: "right" | "top-row" | "bottom-row" | "corners" | "scatter";
  /** The deck breaks the longer headings over two lines. */
  headingLines?: string[];
  /** Which edge the framing art occupies, so the copy column can keep clear of
   *  it instead of running underneath. */
  reserve?: "right" | "top" | "bottom" | "none";
}

/** A piece of the band's framing artwork, lifted from the deck with its alpha
 *  mask and placed where she places it. Purely decorative. */
export interface FramePiece {
  src: string;
  /** Absolute-position classes, relative to the view box. */
  className: string;
}

/** Artwork that sits IN the text flow rather than behind it, so the copy wraps
 *  to its silhouette. `shape-outside` reads the same alpha the image draws with,
 *  so the wrap follows the actual petals and stem — no JS, no traced polygon. */
export interface FloatArt {
  src: string;
  /** Which edge it floats to. Holiday uses both, so the copy runs between the
   *  two garland strands the way the deck frames it. */
  side: "left" | "right";
  /** Width and offset classes. */
  className: string;
  /** Gap held between the silhouette and the text. */
  shapeMargin: string;
}

/**
 * One post from the collection's launch — the THIRD slide of each section in
 * her deck, which is a row of Instagram posts under the product lineup. Ellie
 * asked for these to be "framed and pretty, like you did on the About page"
 * (2026-09-11), so they render in the same <PostCard/> chrome the National
 * Launch wall uses.
 *
 * ⚠️ THE POST LINKS ARE NOT IN THE DECK. Canva cannot rasterise a live embed,
 * so every one of these exports as a blank "View this post on Instagram"
 * placeholder — verified against Downloads/v.pdf at 150dpi, all 15 seasonal
 * cards and all 5 DCC ones. The URLs have to come from Ellie (or the stills
 * do). Until one or the other lands, leave the season's `posts` unset and the
 * row does not render; it does not hold empty frames.
 */
export interface CollectionPost {
  /** Account the post belongs to, e.g. "@maevechocolate". */
  handle: string;
  /** What the post is, in her words. */
  caption: string;
  /** Instagram post URL or bare shortcode. */
  post?: string;
  /** Media aspect, MEASURED off the post's own /embed/ — see InstagramEmbed. */
  aspect?: string;
  /** A still, for a post that cannot be embedded or is not linked yet. */
  image?: { src: string; alt: string };
}

export interface Collection {
  slug: string;
  /** Card label. */
  label: string;
  /** Heading inside the view box, as the deck sets it. */
  briefTitle: string;
  /** The collection's own logotype in the deck, e.g. "CHOCOLATE IS LOVE". */
  wordmark?: string;
  rows: BriefRow[];
  /** Ground colour of the band — sampled from the deck. */
  ground: string;
  /** Display type over that ground. */
  display: string;
  /** Body copy over that ground. */
  body: string;
  motif: string;
  motifAlt: string;
  layout: BandLayout;
  /** Her own band artwork. Falls back to `motif` when a band has none. */
  frame?: FramePiece[];
  /** Artwork the copy flows around instead of stopping short of. */
  floatArt?: FloatArt[];
  /** Outline the display type — Summer's white on ice needs the edge. */
  outlineDisplay?: boolean;
  /**
   * The product lineup that runs under the brief in her deck, under the
   * collection's own logotype. Cropped from the deck at full resolution — the
   * ground is the same blush/sage/etc. as the band, so it sits seamlessly.
   *
   * `height` is the crop's REAL height at 1700 wide, and it has to be right:
   * the image renders `w-full h-auto`, so its shape comes from these numbers
   * rather than from the file. They used to be hard-coded 1700x865 for every
   * season, which squashed Summer's 1700x1205 lineup by a quarter of its height.
   */
  showcase?: { src: string; alt: string; height?: number };
  /** Her third slide: the posts the launch produced. See CollectionPost. */
  posts?: CollectionPost[];
  /**
   * The band rebuilt 1:1 from her deck — brief geometry, edge art, and a stage
   * of measured layers (seasonScenes.ts). When set, SeasonBand renders the
   * band and `frame` / `floatArt` / `showcase` / `wordmark` above are unused;
   * they remain for the collaboration bands, which still compose themselves.
   */
  art?: BandArt;
}

