// How each seasonal band is put together — a 1:1 rebuild of the five bands in
// Ellie's second Canva export (Downloads/v.pdf, page 2, 2026-09-13).
//
// Everything is in DECK UNITS: the deck is a 1024-wide canvas and every band
// is 1024 x 1728, so a value here is a fraction of the band's width. The band
// component turns them into container-query units (`cqw`), so the composition
// scales with the panel and stays in proportion at every width, and an element
// she ran off the edge stays run off the edge.
//
// A band has three parts, top to bottom:
//   1. the brief — her heading, the "In a nutshell" script and the copy. Real
//      text, so it reflows; the geometry below only sets its margins and gaps.
//      `edges` is the artwork pinned around it (corner flowers, the apples arc,
//      the string lights), positioned from the top of the band.
//   2. the stage — a fixed-proportion box holding the products, logotypes and
//      the rest of her artwork, exactly where she placed them. `origin` is the
//      deck y the stage starts at, so a layer at deck y=760 sits 760 - origin
//      from the stage's top. Where her deck sets the Instagram posts INSIDE the
//      composition (Spring's beside the photographs, Summer's flanking the
//      booth), `posts` gives each card its slot here too.
//   3. the posts — for the other bands, the site's card grid under the stage,
//      with any `perches`: the frogs Bart had drawn to sit on Holiday's frames.
//
// The measured layers live in seasonArt.ts, generated by scripts/season-art.py.

