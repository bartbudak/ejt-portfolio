/** One placed piece of her artwork. Measured, not eyeballed. */
export interface ArtLayer {
  name: string;
  src: string;
  /** The file's pixel size, for next/image. */
  px: [number, number];
  /** The box she placed it in: top-left corner and size, deck units. */
  x: number;
  y: number;
  w: number;
  h: number;
  /** Degrees clockwise about the box's centre. */
  rot?: number;
  /** [left, top, right, bottom] cut off the box, deck units — her crop. */
  clip?: [number, number, number, number];
  /** Wrap it in the post card's frame — a photograph standing in a card's place. */
  frame?: boolean;
}

/** A logotype she set as text rather than placed as art. */
export interface TextLayer {
  text: string;
  /** Left edge (or centre, when `align` is "center") and the top of the line box. */
  x: number;
  y: number;
  /** Her point size on the 1024 canvas. */
  size: number;
  color: string;
  align?: "left" | "center";
}

/** Where a post card sits inside the stage: its box's top-left and width, deck
 *  units. Height follows the card's own content. */
export interface PostSlot {
  x: number;
  y: number;
  w: number;
}

export interface Stage {
  origin: number;
  height: number;
  layers: ArtLayer[];
  text?: TextLayer[];
  /** Slots for the band's post cards, in post order. Cards beyond the slots
   *  fall through to the grid below. */
  posts?: PostSlot[];
}

/** Something perched on a post card in the grid — sized and placed as a share
 *  of the card's width, its feet on the frame's outer edge; `hang` is how much
 *  of its own height drops below that edge (icicles over the rim). */
export interface Perch {
  post: number;
  src: string;
  px: [number, number];
  w: number;
  x: number;
  hang: number;
}

/** Where the brief's pieces sit, in deck units, so the reflowing text keeps
 *  her margins and rhythm. */
export interface BriefGeometry {
  /** Deck y of the first thing in the brief (the heading, or the script line
   *  on Holiday, which hangs it above). */
  top: number;
  /** Left edge of a ranged-left heading. Centred bands leave it unset. */
  headingX?: number;
  /** Heading size on the 1024 canvas. Her Benguiat is condensed and Fraunces
   *  is not, so the longer headings come down to hold her line length. */
  headingSize: number;
  /** "In a nutshell": where, and the gap (or overlap, negative) to the heading.
   *  `x` is its left edge for the ranged-left placements. */
  nutshell: {
    at: "below" | "inline" | "above";
    x?: number;
    gap: number;
    /** Point size on the 1024 canvas; 40 unless a band needs it smaller. */
    size?: number;
  };
  /** The copy column: its left and right insets, the gap above it, and whether
   *  she left a blank line between Theme and Launch Campaign. */
  copy: { left: number; right: number; gap: number; paragraphGap: boolean };
  /** Gap between the end of the copy and the stage. */
  stageGap: number;
}

export interface BandArt {
  brief: BriefGeometry;
  edges?: ArtLayer[];
  /** A strip down the band's left edge: `src` drawn once from the top, `tile`
   *  repeated beneath it the rest of the way down. */
  strip?: {
    src: string;
    tile: string;
    px: [number, number];
    w: number;
    h: number;
  };
  stage: Stage;
  perches?: Perch[];
}

const pick = (layers: ArtLayer[], ...names: string[]) =>
  layers.filter((l) => names.includes(l.name));
const rest = (layers: ArtLayer[], ...names: string[]) =>
  layers.filter((l) => !names.includes(l.name));
const tweak = (layers: ArtLayer[], name: string, patch: Partial<ArtLayer>) =>
  layers.map((l) => (l.name === name ? { ...l, ...patch } : l));

